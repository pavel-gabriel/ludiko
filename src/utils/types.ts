export type Difficulty = 'easy' | 'medium' | 'hard';
export type Operation = '+' | '-' | '×' | '÷';
export type Language = 'ro' | 'en';
export type GameType =
  | 'mathRace'
  | 'equations'
  | 'shapeMatch'
  | 'memoryGame'
  | 'countingGame'
  | 'numberSequence';
export type GameCategory = 'math' | 'other';
export type GameMode = 'raceToFinish' | 'timedSprint';
export type ShapeMode = 'image' | 'word';

export interface Player {
  id: string;
  name: string;
  avatar: string;
  score: number;
  isHost: boolean;
  isReady: boolean;
}

export interface Room {
  id: string;
  code: string;
  hostId: string;
  players: Player[];
  status: 'waiting' | 'playing' | 'finished';
  settings: GameSettings;
  createdAt: number;
  /** Classroom session fields (set when room is created via teacher flow) */
  classroomSessionId?: string;
  classroomMode?: ClassroomMode;
  globalTimer?: number;
}

export interface GameSettings {
  gameType: GameType;
  gameMode: GameMode;
  difficulty: Difficulty;
  operations: Operation[];
  rounds: number;
  timePerRound: number;
  shapeMode?: ShapeMode;
  /**
   * v2: skills (src/engine registry ids, e.g. "mat.add.nocarry.20") to practise. When present and
   * non-empty the game runs on shared `Item`s generated for these skills (docs/PLAN.md §7);
   * `gameType` then only picks the mode (memoryGame = memory pairs, anything else = race/sprint).
   * When absent (every room created before v2), the v1 generators are used (see src/services/itemGame.ts).
   * Never store `undefined` here: RTDB rejects it.
   */
  skillIds?: string[];
  /** v2: subject the skills were picked from (informational: shown in the lobby) */
  subject?: string;
}

/** Kind of numeric question — 'math' when absent (backward compatible) */
export type QuestionKind = 'math' | 'counting' | 'sequence' | 'equation';

/** Numeric question (Math Race, Counting, Number Sequence — all modes) */
export interface Question {
  id: string;
  a: number;
  b: number;
  operation: Operation;
  correctAnswer: number;
  options: number[];
  /** Question kind; treated as 'math' when absent */
  kind?: QuestionKind;
  /** Counting: emojis to display (may include distractors on hard) */
  emojis?: string[];
  /** Counting: the emoji the player must count */
  targetEmoji?: string;
  /** Sequence: display string like "2, 4, 6, ?, 10" */
  prompt?: string;
  /** Equation: which operand is hidden ("a + 7 = 15" → 'a') */
  unknown?: 'a' | 'b';
  /** Equation: value on the right of "=" */
  result?: number;
}

/** Shape question (used by Shape Match) */
export interface ShapeQuestion {
  id: string;
  targetShape: string;
  targetLabel: string;
  options: ShapeOption[];
  correctIndex: number;
}

export interface ShapeOption {
  shape: string;
  color: string;
  label: string;
}

/** Memory card (used by Card Flip Memory game) */
export interface MemoryCard {
  id: string;
  pairId: string;
  /** Card face. An emoji in v1; for item-based memory (v2) the text of the face (see `isText`) */
  emoji: string;
  /** v2: the face is text (e.g. "3 + 4" or "7"), not an emoji: shown smaller and wrapped */
  isText?: boolean;
  flipped: boolean;
  matched: boolean;
}

export interface GameSession {
  roomId: string;
  currentRound: number;
  totalRounds: number;
  currentQuestion: Question | null;
  scores: Record<string, number>;
  status: 'countdown' | 'question' | 'result' | 'finished';
  timeRemaining: number;
}

export interface UserPreferences {
  language: Language;
  dyslexicFont: boolean;
  soundEnabled: boolean;
  /** voiceURI chosen for Romanian / English read-aloud (null = best on the device) */
  voiceRo?: string | null;
  voiceEn?: string | null;
  /** read-aloud speed 0.8-1.1 (null = automatic per language and age) */
  voiceRate?: number | null;
}

/* ------------------------------------------------------------------ */
/*  Teacher / Classroom types (Phase 1c)                              */
/* ------------------------------------------------------------------ */

export type ClassroomMode = 'selfPaced' | 'teacherControlled';

/** A teacher profile stored in Firestore */
export interface TeacherProfile {
  uid: string;
  email: string;
  displayName: string;
  createdAt: number;
}

/** A student code generated by the teacher for persistent identity */
export interface StudentCode {
  code: string;
  label: string;
}

/** A classroom session created by a teacher */
export interface ClassroomSession {
  id: string;
  teacherUid: string;
  title: string;
  settings: GameSettings;
  classroomMode: ClassroomMode;
  /** Global timer in seconds (0 = no limit) */
  globalTimer: number;
  studentCodes: StudentCode[];
  /** RTDB room ID once session is started */
  roomId?: string;
  status: 'draft' | 'active' | 'finished';
  createdAt: number;
}

/** Per-student result in a classroom session */
export interface StudentSessionResult {
  studentCode: string;
  studentLabel: string;
  score: number;
  totalQuestions: number;
  accuracy: number;
  timeTaken: number;
  answers: StudentAnswer[];
}

export interface StudentAnswer {
  questionIndex: number;
  selectedAnswer: string;
  correct: boolean;
  timeSpent: number;
}
